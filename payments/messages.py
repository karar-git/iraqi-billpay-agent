def format_iqd(n: int) -> str:
    """50000 -> '50,000'."""
    return f"{n:,}"


def format_period(period: str) -> str:
    """'2026-09' -> 'أيلول 2026' (Iraqi month names); anything else is returned as is."""
    try:
        year, month = period.split("-")
        return f"{MONTHS[int(month)]} {int(year)}"
    except (ValueError, KeyError, AttributeError):
        return period


def render(key: str, gender: str = "f", **slots) -> str:
    """Fill a message. Integers get thousands separators; 'period' gets the month name."""
    template = MESSAGES[key]
    if isinstance(template, dict):
        template = template["m" if gender == "m" else "f"]
    values = {}
    for name, value in slots.items():
        if isinstance(value, int) and not isinstance(value, bool):
            value = format_iqd(value)
        elif name == "period":
            value = format_period(value)
        values[name] = value
    return template.format(**values)


def flag_line(code: str, gender: str = "f", **slots) -> str:
    """Warning line for a soft flag code from payments.rules."""
    return render(f"flag_{code}", gender, **slots)
